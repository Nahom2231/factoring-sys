const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState(
        () => localStorage.getItem("fiep-language") === "am" ? "am" : "en"
    );

    useEffect(() => {
        localStorage.setItem("fiep-language", language);
        document.documentElement.lang = language === "am" ? "am" : "en";
    }, [language]);

    const value = useMemo(() => {
        const t = (text) => {
            if (language !== "am") return text;
            if (typeof text !== "string") return text;
            if (translations[text]) return translations[text];

            let match = text.match(/^(\d+) payments were marked overdue\.$/);
            if (match) return `${match[1]} ክፍያዎች ጊዜያቸው እንዳለፈ ተመዝግበዋል።`;

            match = text.match(/^Delete payment for (.+)\?$/);
            if (match) return `ለ${match[1]} የተመዘገበውን ክፍያ ይሰርዙ?`;

            match = text.match(/^Revoke "(.+)"\? Applications using it will immediately lose access\.$/);
            if (match) return `"${match[1]}" ይሰረዝ? የሚጠቀሙበት መተግበሪያዎች ወዲያውኑ መዳረሻ ያጣሉ።`;

            match = text.match(/^"(.+)" was revoked\.$/);
            if (match) return `"${match[1]}" ተሰርዟል።`;

            match = text.match(/^CREATE API KEY: (.+)$/);
            if (match) return `የAPI ቁልፍ ፈጠረ፡ ${match[1]}`;

            match = text.match(/^REVOKE API KEY: (.+)$/);
            if (match) return `የAPI ቁልፍ ሰረዘ፡ ${match[1]}`;

            match = text.match(/^SWEPT (\d+) OVERDUE PAYMENTS$/);
            if (match) return `${match[1]} ጊዜያቸው ያለፉ ክፍያዎችን አዘምኗል`;

            return text;
        };
        return { language, setLanguage, t };
    }, [language]);

    return (
        <LanguageContext.Provider value={value}>
            {children}
        </LanguageContext.Provider>
    );
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error("useLanguage must be used within LanguageProvider");
    }
    return context;
}
